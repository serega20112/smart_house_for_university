"""Решение человека о судьбе устройств, стоящих на каналах уходящей платы."""

from __future__ import annotations

from enum import StrEnum


class DetachPolicy(StrEnum):
    """Что сделать с устройствами, которые плата оставляет после себя.

    Устройство помнит имя, способности и участие в автоматизации, поэтому
    отвязка платы по умолчанию не стирает ничего: человек либо подтверждает
    судьбу устройств, либо получает их перечень и решает осознанно.

    Attributes:
        REFUSE: Не трогать устройства и ответить их перечнем.
        DETACH: Оставить устройства в доме без платы.
        DELETE: Удалить устройства вместе с их настройкой.
    """

    REFUSE = "refuse"
    DETACH = "detach"
    DELETE = "delete"
