"""Превращение пароля в хранимую форму и сравнение.

Обе операции асинхронны: вывод ключа намеренно дорог, и адаптер обязан уводить
его с цикла событий. Иначе вход одного человека останавливает кадры плат и
сокеты остальных домов ровно на время сверки чужого пароля.
"""

from __future__ import annotations

from abc import ABC, abstractmethod


class PasswordHasher(ABC):
    """Хэширует пароль и проверяет его с хранимой формой."""

    @abstractmethod
    async def hash(self, password: str) -> str:
        """Самоописываемая хранимая форма с солью и стоимостью."""

    @abstractmethod
    async def verify(self, password: str, stored: str | None) -> bool:
        """Совпадает ли введённый пароль с хранимым.

        None означает отсутствие записи: ответ всегда False, но стоимость та же,
        что у настоящей сверки, иначе время ответа выдаёт существование логина.
        Нечитаемая форма — тоже False, а не исключение: испорченная одна строка
        не должна закрывать вход всему сервису.
        """
