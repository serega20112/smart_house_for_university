"""Одноразовый билет, которым открытое WebSocket меняется на сессию.

Браузер не может повесить заголовок авторизации на handshake WebSocket, поэтому токен
приходится передавать в адресе соединения. Держать в адресе сам токен сессии нельзя:
строка запроса попадает в access-логи прокси и сервера, в историю браузера и в Referer,
а токен сессии — это пароль, живой часами. Поэтому REST выдаёт короткий одноразовый
билет, WebSocket один раз обменивает его на аккаунт, и после обмена билет больше не
действует: утёкший адрес безполезен.
"""

from __future__ import annotations

from abc import ABC, abstractmethod

from backend.domain.identifiers import UserId


class RealtimeTicketStore(ABC):
    """Выпускает короткие одноразовые билеты и обменивает их на аккаунт."""

    @abstractmethod
    async def issue(self, user_id: UserId) -> str:
        """Открывает билет на аккаунт.

        Returns:
            str: Непредсказуемая строка билета, годная ровно на один обмен.
        """

    @abstractmethod
    async def redeem(self, ticket: str) -> UserId | None:
        """Обменивает билет на аккаунт ровно один раз.

        Возврат забирает билет: повторный обмен того же билета уже не удаётся.

        Args:
            ticket: Строка билета из строки запроса соединения.

        Returns:
            UserId | None: Аккаунт билета или None, когда билет истёк, неизвестен
                или уже был погашен.
        """
