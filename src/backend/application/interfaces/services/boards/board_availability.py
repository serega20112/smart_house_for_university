"""Спрос «есть ли у аккаунта хоть одна плата в сети».

Доступность дома определяется не тем, что кто-то однажды видел подключение, а живым
реестром присутствия: плата звонится сама, её ключ живёт несколько секунд и продлевается
каждым сообщением. Ответ на этот вопрос даёт тот, кто читает реестр, — поэтому и интерфейс
крошечный: одна проверка, есть ли у аккаунта хоть одна подключённая плата прямо сейчас.
"""

from __future__ import annotations

from abc import ABC, abstractmethod

from backend.domain.identifiers import UserId


class BoardAvailability(ABC):
    """Отвечает, подключена ли сейчас хотя бы одна плата аккаунта."""

    @abstractmethod
    async def is_any_online(self, user_id: UserId) -> bool:
        """True, когда у аккаунта есть хотя бы одна плата в реестре присутствия.

        Args:
            user_id: Владелец дома.

        Returns:
            bool: True при наличии хотя бы одной подключённой платы.
        """
