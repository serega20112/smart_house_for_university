"""Реляционное хранилище: единственный слой системы, знающий, что база существует.

Внутри — всё, что нужно одной таблице, разложенное по папкам так же, как в остальной
инфраструктуре: по файлу на модель, по файлу на хранилище, по файлу на чтение.

``engine``
    асинхронный движок и фабрика сессий, которые композиционный корень строит один раз.
``unit_of_work``
    границы транзакций, по одной на жизнь, и их фабрики.
``models``
    декларативное описание всякой таблицы и метаданные, с которыми сверяют ревизии.
``mappers``
    чистые функции, переводящие агрегаты в строки и строки обратно в агрегаты; они
    общие у стороны записи и стороны чтения, поэтому живут отдельно, а не удваиваются.
``repositories``
    сторона записи: по хранилищу на агрегат, все делят сессию границы транзакции.
``queries``
    сторона чтения: отвечает моделями чтения и транзакцию не открывает.

Схему применяют ревизиями Alembic из ``build/migrations/versions`` и отсюда не создают
никогда, поэтому развёртывание всегда способно построить её с нуля, а схему можно
прочитать как разность в ревью.
"""
