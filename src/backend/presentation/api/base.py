"""Общее поведение моделей HTTP API.

Тела запросов и тела ответов живут в разных пакетах, но проверяются одинаково,
и это единственное место, где правило о лишнем поле записано один раз.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict


class StrictModel(BaseModel):
    """Общее поведение каждого тела API.

    Лишнее поле отбрасывается с ошибкой, а не пропускается дальше: клиент,
    приславший «user_id» там, где его не спрашивали, должен получить отказ, а не
    ощущение, что сервер его услышал.
    """

    model_config = ConfigDict(extra="forbid")
