/**
 * @file claim.h
 * @brief Окно, в котором плата просит себе хозяина.
 *
 * Просьба — жест на самой плате: удерживать FLASH при подаче питания. Индикатора у
 * неё нет: реле — исполнительные органы дома, и мигать ими, сообщая о сопряжении,
 * значит бросать тяжёлую нагрузку на пустом месте. Вся индикация — в serial-логе
 * платы и в интерфейсе того аккаунта, который вошёл.
 *
 * Пока платы никто не забрал, окно открывается снова и снова: человек часто отходит
 * от только что вскрытой коробки и смотрит в интерфейс позже. Плата, у которой уже
 * есть владелец, окно не открывает никогда.
 */

#pragma once

#include <Arduino.h>

/**
 * @brief Открывает окно просьбы о хозяине.
 */
void claimOpen();

/**
 * @brief Закрывает окно, потому что хозяйка или хозяин найден.
 */
void claimClose();

/**
 * @brief Сообщает, открыто ли окно сейчас.
 *
 * @return True, пока плата ждёт, что её заберут.
 */
bool claimWindowOpen();

/**
 * @brief Открывает окно заново, если плата всё ещё ничья, а срок прошёл.
 *
 * Вызывается из главного цикла: решений он не принимает, только следит за моментом.
 */
void claimService();
