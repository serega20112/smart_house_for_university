/**
 * @file relay.h
 * @brief Контакты реле: единственное место, которое знает про пины.
 *
 * Шесть каналов этой платы заняты шестью пинами, а нумерация каналов зафиксирована:
 * сервер только решает, какое логическое устройство за каким каналом стоит, и
 * переназначает устройства без перепрошивки.
 *
 * Модули реле активны низким уровнем: LOW замыкает контакт, HIGH его отпускает.
 * Кроме того, GPIO0 (D3) и GPIO2 (D4) — бутстрап-пины чипа: их состояние при подаче
 * питания решает, уходить ли в загрузчик. Поэтому при старте все пины держатся
 * INPUT_PULLUP (реле разомкнуто), а в OUTPUT они переходят уже после того, как
 * загрузчик отработал.
 */

#pragma once

#include <Arduino.h>

/** Число каналов реле на этой плате. */
static const uint8_t RELAY_COUNT = 6;

/**
 * @brief Готовит пины к работе: разомкнутые контакты, кнопка FLASH читается.
 *
 * Кнопка опрашивается ровно здесь и один раз: дальше пин канала 3 переходит в
 * OUTPUT, и прочесть нажатие после этого было бы невозможно.
 */
void relaysBegin();

/**
 * @brief Сообщает, была ли кнопка FLASH зажата при подаче питания.
 *
 * @return True, когда кнопка удерживалась на старте платы.
 */
bool relaysFlashHeld();

/**
 * @brief Переключает канал и сообщает о нём в журнал платы.
 *
 * @param channel Номер канала, начиная с единицы.
 * @param on True замкнуть контакт, False отпустить.
 */
void relaySet(uint8_t channel, bool on);

/**
 * @brief Сообщает, замкнут ли контакт канала.
 *
 * @param channel Номер канала, начиная с единицы.
 * @return True для замкнутого контакта; канал вне диапазона считается разомкнутым.
 */
bool relayIsOn(uint8_t channel);

/**
 * @brief Выкладывает положения всех каналов массивом по порядку.
 *
 * Кадр STATE строит транспорт, и строит он его документом JSON: положения нужны
 * именно булевыми значениями, а не списком слов, чтобы сериализатор сам следил за
 * запятыми и экранированием.
 *
 * @param out Буфер, куда ложатся положения.
 * @param capacity Сколько мест в буфере (записывается не больше RELAY_COUNT).
 */
void relaysSnapshot(bool *out, size_t capacity);
