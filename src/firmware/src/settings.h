/**
 * @file settings.h
 * @brief Сеть платы и сервер, которому она докладывается, в оперативной памяти.
 *
 * Значения приходят от владельца — со страницы настройки на собственной точке
 * доступа платы или кадром SET_NETWORK от сервера, — и в обоих случаях они
 * ложатся в флеш-память чипа. Поэтому ни адреса, ни пароля в коде нет: одна сборка
 * подходит всем платам, и после перезапуска питания настройки остаются на месте.
 */

#pragma once

#include "network_config.h"

/**
 * @brief Читает сеть из памяти платы и пишет её в оперативную память.
 *
 * @return True, когда плату уже настраивали.
 */
bool settingsLoad();

/**
 * @brief Возвращает действующие настройки сети.
 *
 * @return Конфигурация, которой плата пользуется прямо сейчас.
 */
const NetworkConfig &settingsCurrent();

/**
 * @brief Заменяет настройки и пишет их во флеш-память платы.
 *
 * @param config Новые значения.
 */
void settingsSave(const NetworkConfig &config);
