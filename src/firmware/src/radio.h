/**
 * @file radio.h
 * @brief Радиомодуль платы: вход в сеть и удержание связи.
 *
 * Копию настроек чип хранит у себя во флеше, а плате это не нужно: две копии
 * стирали бы память вдвое и могли бы разойтись после пропадания питания, поэтому
 * ядру велено ничего не сохранять, а сеть присоединяется по имени из настроек платы.
 */

#pragma once

#include <Arduino.h>

/** Сколько секунд плата ждёт присоединения к сети. */
static const unsigned long RADIO_JOIN_TIMEOUT_MS = 20000;

/** Как часто плата пробует вернуться в сеть, если связь потеряна. */
static const unsigned long RADIO_RETRY_MS = 5000;

/**
 * @brief Пробует войти в сеть, которую указали настройки платы.
 *
 * @param timeoutMs Сколько секунд на это отводится.
 * @return True, когда плата в сети.
 */
bool radioJoin(unsigned long timeoutMs);

/**
 * @brief Сообщает, есть ли связь.
 *
 * @return True, когда плата присоединена к сети.
 */
bool radioLinked();

/**
 * @brief Заставляет радиомодуль поискать сеть заново, если связь пропала.
 *
 * Вызывается из главного цикла. Повторный запрос идёт не на каждой итерации: ядро
 * ставит запрос в очередь, и второй лишь отнял бы у платы время, нужное первому.
 *
 * @return True, когда плата в сети.
 */
bool radioKeepAlive();

/**
 * @brief Отпускает сеть: следующим её ищет владелец новых настроек.
 */
void radioLeave();
