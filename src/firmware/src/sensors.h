/**
 * @file sensors.h
 * @brief DHT22: температура и влажность, которые плата измеряет сама.
 *
 * Датчик отвечает медленно и не терпит опроса чаще, чем раз в две секунды, поэтому
 * чтение живёт своим интервалом и никогда не вызывается из разбора кадра: плата
 * обязана отвечать серверу даже тогда, когда датчик молчит.
 */

#pragma once

#include <Arduino.h>

/**
 * @brief Готовит датчик к работе.
 */
void sensorsBegin();

/**
 * @brief Читает датчик, если с прошлого чтения прошло достаточно времени.
 */
void sensorsRead();

/**
 * @brief Сообщает, есть ли валидные показания.
 *
 * @return True, когда и температура, и влажность получены.
 */
bool sensorsReady();

/**
 * @brief Возвращает последнюю измеренную температуру в градусах Цельсия.
 *
 * @return Температура либо NaN, если датчик ещё не ответил.
 */
float sensorsTemperature();

/**
 * @brief Возвращает последнюю измеренную относительную влажность.
 *
 * @return Влажность в процентах либо NaN, если датчик ещё не ответил.
 */
float sensorsHumidity();
