/**
 * @file identity.h
 * @brief Личность платы: ключ, который она предъявляет серверу, и её владелец.
 *
 * Ключ не хранится в коде: на первом включении плата вырабатывает его сама и
 * держит в своей флеш-памяти. Поэтому одна и та же прошивка уходит всем, а
 * перепрошивать плату ради привязки не нужно.
 *
 * Флаг «у меня есть владелец» — только кеш последнего ответа сервера: сервер
 * решает сам, кому принадлежит плата, и если он скажет «не знаю», кеш обязан
 * сброситься.
 */

#pragma once

#include <Arduino.h>

#include "config_store.h"

/**
 * @brief Читает ключ из памяти платы, а если его нет — вырабатывает и сохраняет.
 */
void identityBegin();

/**
 * @brief Возвращает ключ, с которым плата звонится на сервер.
 *
 * @return Ключ, оканчивающийся нулём.
 */
const char *identityKey();

/**
 * @brief Возвращает метку платы — короткий код, показываемый в интерфейсе.
 *
 * @param out Буфер, куда записывается метка.
 * @param capacity Размер этого буфера.
 */
void identityLabel(char *out, size_t capacity);

/**
 * @brief Сообщает, считает ли себя плата принадлежащей аккаунту.
 *
 * @return True, если флаг владения поднят.
 */
bool identityHasOwner();

/**
 * @brief Записывает, что плата принадлежит аккаунту.
 */
void identityMarkOwned();

/**
 * @brief Забывает владение и отпускает плату искать хозяина заново.
 */
void identityForgetOwner();
